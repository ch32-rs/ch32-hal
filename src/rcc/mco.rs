//! Microcontroller clock output (MCO).
//!
//! The MCO output is configured after [`crate::rcc::init`], because it borrows
//! the pin that carries the signal. The driver writes `RCC_CFGR0.MCO` and
//! switches the pin to alternate-function push-pull; it does not change the
//! clock tree.
//!
//! Pin assignment differs across the series:
//!
//! | Family | Pin |
//! | --- | --- |
//! | CH32V1/V2/V3/V4, CH32L1 | PA8 |
//! | CH32V0 | PC4 |
//! | CH32X0, CH643 | PB9 |
//! | CH641 | PB7 |
//! | CH32H4 | PB0 (AF0) |
//!
//! The valid pins come from the ch32-data pin tables; the `McoPin` impls are
//! generated by `build.rs`.

use crate::gpio::{AfType, AnyPin, OutputType, Pin, Speed};
// `McoSource` is the PAC `vals::Mco` enum once the pinned ch32-metapac carries
// it for the active RCC version. rcc_v1 and rcc_v4x7 got the enum later than
// the others, so until then build.rs leaves `ch32_mco_enum` unset and we use a
// local `#[repr(u8)]` enum with the same variant names instead.
#[cfg(ch32_mco_enum)]
pub use crate::pac::rcc::vals::Mco as McoSource;
use crate::pac::RCC;
use crate::Peri;

/// CH32V1/RCC v1 selects the source with a three-bit field.
#[cfg(all(not(ch32_mco_enum), rcc_v1))]
#[allow(non_camel_case_types)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u8)]
pub enum McoSource {
    NO_CLK = 0b000,
    SYSCLK = 0b100,
    HSI = 0b101,
    HSE = 0b110,
    PLL_DIV2 = 0b111,
}

/// CH32V407/CH32V467 selects the source with a four-bit field.
///
/// RM §3.3.5.5: values `00xx` produce no clock; the remaining listed values
/// select SYSCLK, HSI, HSE, UTMI, ETH_PLL/8 and XT1.
#[cfg(all(not(ch32_mco_enum), rcc_v4x7))]
#[allow(non_camel_case_types)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u8)]
pub enum McoSource {
    NO_CLK = 0b0000,
    SYSCLK = 0b0100,
    HSI = 0b0101,
    HSE = 0b0110,
    UTMI = 0b0111,
    ETH_PLL_DIV8 = 0b1000,
    XT1 = 0b1010,
}

/// Pin that can carry the MCO signal.
#[cfg(not(afio_h4))]
pub trait McoPin: Pin {}

/// Pin that can carry the MCO signal, including its CH32H4 AF number.
#[cfg(afio_h4)]
pub trait McoPin: Pin {
    fn af_num(&self) -> u8;
}

// H4's MCO pin (PB0/AF0) is the one data entry that arrived after the pinned
// PAC. `build.rs` emits `ch32_data_h4_mco_pin` and generates the impl from the
// pin table once the data carries it; until then this fallback keeps PB0
// usable.
#[cfg(all(rcc_h4, not(ch32_data_h4_mco_pin)))]
impl McoPin for crate::peripherals::PB0 {
    fn af_num(&self) -> u8 {
        0
    }
}

/// MCO output driver.
///
/// Holds the pin for the lifetime of the output. Dropping it releases the pin
/// but leaves `RCC_CFGR0.MCO` and the pin mode unchanged, matching the other
/// clock outputs.
pub struct Mco<'d> {
    _pin: Peri<'d, AnyPin>,
}

impl<'d> Mco<'d> {
    /// Select `source` on MCO and configure `pin` as alternate-function
    /// push-pull.
    pub fn new(pin: Peri<'d, impl McoPin>, source: McoSource) -> Self {
        critical_section::with(|_| {
            #[cfg(ch32_mco_enum)]
            RCC.cfgr0().modify(|w| w.set_mco(source));
            #[cfg(not(ch32_mco_enum))]
            RCC.cfgr0().modify(|w| w.set_mco(source as u8));
        });

        pin.set_as_af(
            // CH32H4 selects the function with the pin's AF number
            // (`AFIO.GPIO_AFR`); every other family uses the legacy AF
            // push-pull CNF and needs no number.
            #[cfg(afio_h4)]
            pin.af_num(),
            AfType::output(OutputType::PushPull, Speed::High),
        );
        let pin: Peri<'d, AnyPin> = pin.into();

        Self { _pin: pin }
    }
}
